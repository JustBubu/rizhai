/** 若栏目标题仍是某一语言的默认值，切换到目标语言对应标题。 */
export function remapDefaultSectionTitles<T extends { id: string; title: string }>(
  sections: T[],
  locale: Locale,
): T[] {
  const titleToTarget = new Map<string, string>();
  for (const localeKey of Object.keys(DEFAULT_SECTION_TITLES) as Locale[]) {
    const source = DEFAULT_SECTION_TITLES[localeKey];
    const target = DEFAULT_SECTION_TITLES[locale];
    for (let i = 0; i < source.length; i += 1) {
      titleToTarget.set(source[i].title, target[i]?.title ?? source[i].title);
    }
  }
  return sections.map((section) => {
    const next = titleToTarget.get(section.title);
    return next && next !== section.title ? { ...section, title: next } : section;
  });
}

